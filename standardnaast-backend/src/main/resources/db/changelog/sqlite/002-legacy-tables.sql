CREATE TABLE TYPE_COMPETITION (
    TYPE_COMPETITION_ID BIGINT PRIMARY KEY NOT NULL,
    TYPE_COMPETITION_VALUE VARCHAR(100) NOT NULL
);
CREATE TABLE TYPE_MATCH (
    TYPE_MATCH_ID BIGINT PRIMARY KEY NOT NULL,
    TYPE_COMPETITION_ID BIGINT NOT NULL REFERENCES TYPE_COMPETITION(TYPE_COMPETITION_ID),
    DENOMINATION_MATCH VARCHAR(100) NOT NULL
);
CREATE TABLE TYPE_PERSONNE (
    TYPE_PERSONNE_ID BIGINT PRIMARY KEY NOT NULL,
    DENOMINATION_TYPE_PERSONNE VARCHAR(100) NOT NULL,
    AGE_MINIMUM INT,
    AGE_MAXIMUM INT,
    ETUDIANT INT,
    MEMBRE INT,
    TARIF INT
);
CREATE TABLE PRIX_PLACE (
    PRIX_PLACE_ID BIGINT PRIMARY KEY NOT NULL,
    BLOC_ID VARCHAR(100) NOT NULL,
    TYPE_PERSONNE_ID BIGINT NOT NULL REFERENCES TYPE_PERSONNE(TYPE_PERSONNE_ID),
    TYPE_MATCH_ID BIGINT NOT NULL REFERENCES TYPE_MATCH(TYPE_MATCH_ID),
    MONTANT NUMERIC NOT NULL,
    SAISON VARCHAR(10) NOT NULL REFERENCES SAISON(SAISON_ID),
    TARIF NUMERIC,
    ABONNE NUMERIC
);
CREATE TABLE COMMANDE_PLACE (
    COMMANDE_PLACE_ID BIGINT PRIMARY KEY NOT NULL,
    PERSONNE_ID BIGINT NOT NULL REFERENCES PERSONNES(PERSONNE_ID),
    MATCH_ID BIGINT NOT NULL REFERENCES MATCH(MATCH_ID),
    DATE_COMMANDE TIMESTAMP NOT NULL,
    NOMBRE_PLACE INT NOT NULL,
    TYPE_PLACE VARCHAR(4000),
    BLOC_ID BIGINT REFERENCES BLOC(BLOC_ID),
    PLACE_COMMANDEE INT NOT NULL
);
