CREATE TABLE SAISON (
    SAISON_ID VARCHAR(10) PRIMARY KEY NOT NULL,
    DATE_DEBUT DATE NOT NULL,
    DATE_FIN DATE NOT NULL,
    DATE_PREMIER_MATCH_CHAMPIONNAT DATE,
    EUROPEENS BOOLEAN,
    MONTANT_COTISATION NUMERIC(19, 2)
);
CREATE TABLE EQUIPE (
    EQUIPE_ID INTEGER PRIMARY KEY AUTOINCREMENT,
    NOM_EQUIPE VARCHAR(150) NOT NULL
);
CREATE TABLE COTISATIONS (
    ANNEE_COTISATION2 BIGINT PRIMARY KEY NOT NULL,
    ANNEE_COTISATION VARCHAR(4),
    MONTANT_COTISATION NUMERIC(10, 2) NOT NULL
);
CREATE TABLE ACCOUNTING (
    ID INTEGER PRIMARY KEY AUTOINCREMENT,
    ACCOUNTING_DATE DATE,
    DESCRIPTION VARCHAR(256),
    TYPE VARCHAR(5),
    AMOUNT NUMERIC(19, 2)
);
CREATE TABLE PERSONNES (
    PERSONNE_ID INTEGER PRIMARY KEY AUTOINCREMENT,
    NOM VARCHAR(100) NOT NULL,
    PRENOM VARCHAR(100),
    ADRESSE VARCHAR(200),
    CODE_POSTAL VARCHAR(10),
    VILLE VARCHAR(100),
    TELEPHONE VARCHAR(20),
    GSM VARCHAR(20),
    EMAIL VARCHAR(120),
    DATE_NAISSANCE DATE,
    NUMERO_MEMBRE BIGINT,
    CARTE_IDENTITE VARCHAR(50),
    ETUDIANT BOOLEAN,
    VALIDITE_CARTE_IDENTITE DATE,
    RED_CARD BOOLEAN DEFAULT FALSE,
    CUS VARCHAR(50),
    ROBOTICKET_ID VARCHAR(50)
);
CREATE TABLE SAISON_EQUIPE (
    SAISON_EQUIPE_ID INTEGER PRIMARY KEY AUTOINCREMENT,
    SAISON_ID VARCHAR(10) NOT NULL REFERENCES SAISON(SAISON_ID),
    EQUIPE_ID BIGINT NOT NULL REFERENCES EQUIPE(EQUIPE_ID)
);
CREATE TABLE PRICES (
    ID INTEGER PRIMARY KEY AUTOINCREMENT,
    SAISON_ID VARCHAR(10) NOT NULL REFERENCES SAISON(SAISON_ID),
    PRIX BIGINT NOT NULL,
    TRIBUNE INT,
    BLOC VARCHAR(50) NOT NULL,
    TYPE_PERSONNE VARCHAR(50),
    TYPE_COMPETITION VARCHAR(50) NOT NULL,
    RANG VARCHAR(50),
    PLACE VARCHAR(50),
    PRICE_TYPE VARCHAR(20) NOT NULL
);
CREATE TABLE TRAVEL_PRICE (
    ID INTEGER PRIMARY KEY AUTOINCREMENT,
    SEASON_ID VARCHAR(10) REFERENCES SAISON(SAISON_ID),
    MONTANT NUMERIC(19, 2) NOT NULL,
    PLACE VARCHAR(50) NOT NULL,
    MEMBRE BOOLEAN NOT NULL,
    TYPE_PERSONNE VARCHAR(50)
);
CREATE TABLE BENEVOLAT (
    BENEVOLAT_ID INTEGER PRIMARY KEY AUTOINCREMENT,
    PERSONNE_ID BIGINT NOT NULL REFERENCES PERSONNES(PERSONNE_ID),
    MONTANT NUMERIC(19, 2),
    TYPE_BENEVOLAT VARCHAR(100),
    DATE_BENEVOLAT DATE
);
CREATE TABLE PERSONNES_COTISATIONS (
    ID INTEGER PRIMARY KEY AUTOINCREMENT,
    PERSONNE_ID BIGINT NOT NULL REFERENCES PERSONNES(PERSONNE_ID),
    SEASON_ID VARCHAR(10) NOT NULL REFERENCES SAISON(SAISON_ID),
    DATE_PAIEMENT DATE,
    CARTE_MEMBRE_ENVOYEE BOOLEAN NOT NULL DEFAULT FALSE,
    ANNEE_COTISATION VARCHAR(4)
);
CREATE TABLE MATCH (
    MATCH_ID INTEGER PRIMARY KEY AUTOINCREMENT,
    SAISON_ID VARCHAR(10) NOT NULL REFERENCES SAISON(SAISON_ID),
    OPPONENT BIGINT NOT NULL REFERENCES EQUIPE(EQUIPE_ID),
    SAISON_EQUIPE_ID BIGINT REFERENCES SAISON_EQUIPE(SAISON_EQUIPE_ID),
    DATE_MATCH TIMESTAMP,
    PLACE VARCHAR(50) NOT NULL,
    COMPETITION_TYPE VARCHAR(16) NOT NULL,
    MATCH_TYPE VARCHAR(19),
    PRICE_TYPE VARCHAR(6)
);
CREATE TABLE PERSONNE_MATCH (
    ID INTEGER PRIMARY KEY AUTOINCREMENT,
    PERSONNE_ID BIGINT NOT NULL REFERENCES PERSONNES(PERSONNE_ID),
    MATCH_ID BIGINT NOT NULL REFERENCES MATCH(MATCH_ID),
    CAR_TRAVEL_AMOUNT BIGINT NOT NULL,
    PRIX_LOCOMOTION_ID BIGINT REFERENCES TRAVEL_PRICE(ID)
);
CREATE TABLE BLOC (
    BLOC_ID BIGINT PRIMARY KEY NOT NULL,
    BLOC_VALUE VARCHAR(50) NOT NULL,
    TRIBUNE VARCHAR(100),
    CLUB VARCHAR(200) NOT NULL,
    EQUIPE_ID BIGINT REFERENCES EQUIPE(EQUIPE_ID)
);
CREATE TABLE ABONNEMENT (
    ABONNEMENT_ID INTEGER PRIMARY KEY AUTOINCREMENT,
    PERSONNE_ID BIGINT REFERENCES PERSONNES(PERSONNE_ID),
    SAISON VARCHAR(10) NOT NULL REFERENCES SAISON(SAISON_ID),
    PRICES_ID BIGINT REFERENCES PRICES(ID),
    RANG VARCHAR(6),
    PLACE VARCHAR(100),
    REDUCTION BIGINT NOT NULL,
    PAYE BOOLEAN NOT NULL,
    ACOMPTE BIGINT,
    ABONNEMENT_STATUS VARCHAR(20),
    BLOC_VALUE VARCHAR(50),
    BLOC_ID BIGINT REFERENCES BLOC(BLOC_ID)
);
CREATE TABLE APP_USERS (
    USER_ID INTEGER PRIMARY KEY AUTOINCREMENT,
    USERNAME VARCHAR(50) NOT NULL UNIQUE,
    PASSWORD VARCHAR(255) NOT NULL,
    EMAIL VARCHAR(100) UNIQUE,
    FIRSTNAME VARCHAR(50),
    LASTNAME VARCHAR(50),
    ENABLED BOOLEAN NOT NULL DEFAULT TRUE,
    PERSONNE_ID BIGINT UNIQUE REFERENCES PERSONNES(PERSONNE_ID),
    CREATED_AT TIMESTAMP,
    UPDATED_AT TIMESTAMP
);
CREATE TABLE APP_USER_ROLES (
    USER_ID BIGINT NOT NULL REFERENCES APP_USERS(USER_ID),
    ROLE VARCHAR(50) NOT NULL,
    PRIMARY KEY (USER_ID, ROLE)
);
